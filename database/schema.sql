CREATE TABLE IF NOT EXISTS categories (
  id INT UNSIGNED PRIMARY KEY AUTO_INCREMENT,
  code VARCHAR(30) NOT NULL UNIQUE,
  name VARCHAR(150) NOT NULL UNIQUE,
  specs TEXT,
  status VARCHAR(60) NOT NULL DEFAULT 'Đang dùng'
) ENGINE=InnoDB;

CREATE TABLE IF NOT EXISTS brands (
  id INT UNSIGNED PRIMARY KEY AUTO_INCREMENT,
  name VARCHAR(150) NOT NULL UNIQUE,
  status VARCHAR(60) NOT NULL DEFAULT 'Đang dùng'
) ENGINE=InnoDB;

CREATE TABLE IF NOT EXISTS products (
  id INT UNSIGNED PRIMARY KEY AUTO_INCREMENT,
  sku VARCHAR(60) NOT NULL UNIQUE,
  barcode VARCHAR(60) UNIQUE,
  name VARCHAR(255) NOT NULL,
  category_id INT UNSIGNED NOT NULL,
  brand_id INT UNSIGNED NOT NULL,
  price DECIMAL(15,2) NOT NULL DEFAULT 0,
  avg_cost DECIMAL(15,2) NOT NULL DEFAULT 0,
  stock INT UNSIGNED NOT NULL DEFAULT 0,
  min_stock INT UNSIGNED NOT NULL DEFAULT 0,
  warranty_months INT UNSIGNED NOT NULL DEFAULT 0,
  serial_managed BOOLEAN NOT NULL DEFAULT FALSE,
  status VARCHAR(60) NOT NULL DEFAULT 'Đang kinh doanh',
  specs TEXT,
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  FOREIGN KEY (category_id) REFERENCES categories(id),
  FOREIGN KEY (brand_id) REFERENCES brands(id),
  CHECK (price >= 0), CHECK (avg_cost >= 0)
) ENGINE=InnoDB;
